    <h2 id="terms">Основные понятия</h2>
    <dl class="guide__terms">
      <dt>Категория</dt><dd>Тема новости, например «Образование» или «Транспорт». По категориям читатель находит новости на интересную ему тему.</dd>
      <dt>Территория</dt><dd>Любое место, к которому относится новость (вид места не ограничивается), например «Ангарск» или «Слюдянский район». По территориям читатель находит новости своего населённого пункта.</dd>
      <dt>Предложение</dt><dd>Просьба журналиста добавить категорию или территорию, которой пока нет в списке, или исправить написание существующей записи.</dd>
      <dt>Состояние предложения</dt><dd>«Новое» – ожидает решения менеджера; «добавлено» – менеджер добавил запись; «исправлено» – менеджер заблокировал запись с ошибкой и добавил запись в правильном написании.</dd>
      <dt>Блокировка</dt><dd>Заблокированная запись не выдаётся журналисту для выбора, но не удаляется: опубликованные ранее новости остаются отнесёнными к ней.</dd>
      <dt>Структура портала</dt><dd>Списки категорий и территорий, по которым распределяются все новости портала.</dd>
    </dl>

    <h2 id="journalist">Журналисту</h2>
    <ol>
      <li>При заполнении новостного материала выберите категорию и территорию.</li>
      <li>Если нужной записи нет, откройте блок «Предложить», выберите, что предлагаете – категорию или территорию, – и введите наименование.</li>
      <li>Нажмите «Отправить предложение». Система сразу сравнит введённое наименование с действующими записями и выведет один из ответов:
        <ul>
          <li>запись есть в том же написании – выберите её в поле формы;</li>
          <li>запись есть, но написана иначе (например, «Усть-кут» вместо «Усть-Кут») – выберите существующую запись или, если она написана неверно, нажмите «Сообщить: правильно …»;</li>
          <li>записи нет – предложение отправлено менеджеру.</li>
        </ul>
      </li>
      <li>После того как менеджер добавит запись, её можно будет выбрать в форме.</li>
    </ol>

    <h2 id="manager">Менеджеру</h2>
    <ol>
      <li>При вводе портала в эксплуатацию заполните списки сами: на страницах «Категории» и «Территории» нажмите «Добавить категорию» / «Добавить территорию». Территории вносятся по карте Иркутской области, затем – по предложениям журналистов.</li>
      <li>Страница «Предложения» показывает предложения в состоянии «новое» в порядке поступления: старые сверху. Нажмите «Добавить» или «Исправить» напротив предложения. Проверьте наименование и приведите его к принятому написанию.</li>
      <li>Для категории при необходимости добавьте описание. Нажмите «Сохранить».</li>
      <li>Изменяйте запись через «Изменить», только пока она не указана в опубликованных новостях. Если запись уже использована, нажмите «Заблокировать» и добавьте запись заново.</li>
    </ol>

